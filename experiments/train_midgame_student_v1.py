#!/usr/bin/env python3
"""Build and train the first real step-288 candidate-selection student.

This is deliberately not the per-cell policy: the native teacher does not yet
export exact per-prefix legal masks/resource calendars.  It learns only among
the normal complete portfolios already generated by R1.  ``short_score`` is a
target-only field and never enters ``forward``.
"""

from __future__ import annotations

import argparse
import copy
import ctypes
import gzip
import hashlib
import json
import math
import os
import struct
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
TOKENIZER_ROOT = Path("/root/kaggriculture_transformer_ppo_starter")
MODEL_INPUTS = {
    "causal_context", "packed_observation", "observation_length",
    "token_continuous", "token_type", "token_category_a", "token_category_b",
    "token_category_c", "token_x", "token_y", "token_owner", "token_count",
    "candidate_features", "candidate_target", "state_candidate_offsets",
}


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _json_hash(value) -> str:
    payload = json.dumps(value, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(payload).hexdigest()


def _validate_trajectory(path: Path, expected: dict) -> dict:
    meta = None
    steps = []
    terminals = 0
    with gzip.open(path, "rt", encoding="utf-8") as source:
        for line in source:
            row = json.loads(line)
            if row.get("type") == "meta":
                if meta is not None:
                    raise ValueError(f"{path}: multiple meta rows")
                meta = row
            elif row.get("type") == "step":
                steps.append(int(row["step"]))
            elif row.get("type") == "terminal":
                terminals += 1
    if meta is None or steps != list(range(719)) or terminals != 1:
        raise ValueError(f"{path}: expected one meta, steps 0..718, one terminal")
    for key in ("seed", "seat"):
        if int(meta.get(key, -1)) != int(expected[key]):
            raise ValueError(f"{path}: {key} mismatch")
    if meta.get("bot") != expected["opponent"]:
        raise ValueError(f"{path}: opponent mismatch")
    if meta.get("format") != expected["trajectory_format"]:
        raise ValueError(f"{path}: trajectory format mismatch")
    if meta.get("diagnostic") is not False:
        raise ValueError(f"{path}: diagnostic/unknown trajectory is not training data")
    if meta.get("policy_manifest_canonical_sha256") != expected["policy_sha256"]:
        raise ValueError(f"{path}: deployment policy digest mismatch")
    return meta


def _canonical_observation(observation: dict) -> dict:
    """Put the acting farm first and erase seat identity."""
    result = copy.deepcopy(observation)
    player = int(result.pop("player", 0))
    farms = list(result["farms"])
    if len(farms) != 2 or player not in (0, 1):
        raise ValueError("expected a two-player observation")
    result["farms"] = [farms[player], farms[1 - player]]
    result["player"] = 0
    return result


def _extract_state(job: dict) -> dict:
    # Each native handle lives in its own process; the bridge intentionally
    # rejects multi-handle batching in one process.
    from experiments.audit_teacher_batch import (
        bind, candidate_features, candidate_key, causal_context, key_hash128,
        names_from, names_sha256, r1_module, restore,
    )

    path = Path(job["trajectory"])
    meta = _validate_trajectory(path, job)
    module = r1_module()
    agent, restored_meta, observation, values = restore(
        module, Path(job["binary"]), path, 288)
    try:
        if restored_meta != meta:
            raise RuntimeError(f"{path}: metadata changed between validation and restore")
        lib = agent.lib
        bind(lib)
        contract = json.loads(lib.td_teacher_contract_json())
        if lib.td_teacher_abi_version() != 2 or contract.get("abi_version") != 2:
            raise RuntimeError("teacher ABI v2 required")
        packed = (ctypes.c_double * len(values))(*values)
        count = lib.td_teacher_prepare_features_observation(
            agent.handle, packed, len(packed))
        if count <= 0:
            raise RuntimeError(lib.td_debug(agent.handle).decode())
        feature_names = names_from(lib, "td_teacher_candidate_feature_names", agent.handle)
        context_names = names_from(lib, "td_teacher_context_names", agent.handle)
        if (len(feature_names) != contract["candidate_feature_width"] or
                len(context_names) != contract["causal_context_width"] or
                names_sha256(feature_names) != contract["candidate_feature_names_sha256"] or
                names_sha256(context_names) != contract["causal_context_names_sha256"]):
            raise RuntimeError("native schema width/hash mismatch")
        context = causal_context(lib, agent.handle, len(context_names))

        candidates = []
        for index in range(count):
            key = candidate_key(lib, agent.handle, index)
            targets = (ctypes.c_int32 * 200)()
            target_count = lib.td_teacher_candidate_targets(
                agent.handle, index, targets, len(targets))
            if target_count <= 0:
                raise RuntimeError(f"candidate {index}: target export failed")
            # Native portfolio target uses -1 for an intentionally empty cell;
            # -2 is our padding for locked/non-target cells.
            target = [-2] * 100
            for at in range(target_count):
                cell, kind = int(targets[2 * at]), int(targets[2 * at + 1])
                if not 0 <= cell < 100 or not -1 <= kind <= 11 or target[cell] != -2:
                    raise RuntimeError(f"candidate {index}: invalid target entry")
                target[cell] = kind
            candidates.append({
                "prepared_index": index,
                "candidate_id": int(lib.td_candidate_id(agent.handle, index)),
                "key_hash128": key_hash128(key),
                "features": candidate_features(lib, agent.handle, index, len(feature_names)),
                "target": target,
            })

        # This is the one expensive teacher call needed for the temporary
        # target.  It scores all prepared proposals but does no scenario suffix.
        started = time.perf_counter()
        scored = agent.prepare_candidates(observation, with_features=False)
        score_seconds = time.perf_counter() - started
        normal = {int(row["index"]): row for row in scored if row.get("diagnostic", "") == ""}
        if set(normal) != set(range(count)):
            raise RuntimeError("feature-only normal candidates differ from short-score normals")
        for candidate in candidates:
            index = candidate["prepared_index"]
            row = normal[index]
            if int(row["id"]) != candidate["candidate_id"]:
                raise RuntimeError("candidate id changed during short-score prepare")
            if key_hash128(candidate_key(lib, agent.handle, index)) != candidate["key_hash128"]:
                raise RuntimeError("candidate key changed during short-score prepare")
            score = float(row["score"])
            if not math.isfinite(score):
                raise RuntimeError("non-finite short score")
            candidate["short_score"] = score
        winner = max(range(count), key=lambda index: candidates[index]["short_score"])
        if causal_context(lib, agent.handle, len(context_names)) != context:
            raise RuntimeError("short-score prepare mutated exported causal context")

        canonical = _canonical_observation(observation)
        exact_packed = [float(value) for value in module._pack(canonical)]
        return {
            "seed": int(meta["seed"]),
            "seat": int(meta["seat"]),
            "opponent": str(meta["bot"]),
            "trajectory": str(path),
            "policy_sha256": meta["policy_manifest_canonical_sha256"],
            "contract": contract,
            "feature_names": feature_names,
            "context_names": context_names,
            "context": context,
            "observation": canonical,
            "packed_observation": exact_packed,
            "candidates": candidates,
            "winner_local": winner,
            "short_score_seconds": score_seconds,
        }
    finally:
        agent.close()


def _source_jobs(allowlist_path: Path, binary: Path, max_states: int) -> tuple[list[dict], dict]:
    allowlist = json.loads(allowlist_path.read_text())
    if (allowlist.get("format") != "kaggriculture-bc-source-allowlist-v1" or
            allowlist.get("validation_status") != "accepted"):
        raise ValueError("source allowlist must be explicitly accepted")
    jobs = []
    seen_paths = set()
    seen_groups = set()
    for source in allowlist.get("sources", []):
        manifest_path = (ROOT / source["result_manifest"]).resolve()
        if _sha256(manifest_path) != source["result_manifest_sha256"]:
            raise ValueError(f"{manifest_path}: source manifest digest mismatch")
        result = json.loads(manifest_path.read_text())
        for key in ("seed_range", "trajectory_format"):
            if result.get(key) != source[key]:
                raise ValueError(f"{manifest_path}: {key} mismatch")
        if result.get("policy_manifest_canonical_sha256") != source["policy_manifest_canonical_sha256"]:
            raise ValueError(f"{manifest_path}: policy digest mismatch")
        if result.get("diagnostic") is not source["diagnostic"]:
            raise ValueError(f"{manifest_path}: diagnostic flag mismatch")
        rows = {}
        for row in result.get("rows", []):
            opponent = row.get("opponent", row.get("bot"))
            key = (int(row["seed"]), opponent, int(row["seat"]))
            if key in rows:
                raise ValueError(f"{manifest_path}: duplicate result row {key}")
            rows[key] = row
        start, stop = map(int, source["seed_range"])
        opponents = list(source["opponents"])
        seats = list(map(int, source["seats"]))
        for seed in range(start, stop):
            opponent = opponents[(seed - start) % len(opponents)]
            for seat in seats:
                row = rows.get((seed, opponent, seat))
                if not row or row.get("error") is not None:
                    raise ValueError(f"{manifest_path}: missing clean row {(seed, opponent, seat)}")
                trajectory = Path(row["trajectory"])
                if not trajectory.is_absolute():
                    trajectory = (ROOT / trajectory).resolve()
                group = (seed, opponent)
                if trajectory in seen_paths or group in seen_groups:
                    raise ValueError("duplicate trajectory or (seed, opponent) group")
                seen_paths.add(trajectory)
                seen_groups.add(group)
                jobs.append({
                    "trajectory": str(trajectory), "seed": seed, "seat": seat,
                    "opponent": opponent, "trajectory_format": source["trajectory_format"],
                    "policy_sha256": source["policy_manifest_canonical_sha256"],
                    "binary": str(binary.resolve()),
                })
                if len(jobs) == max_states:
                    return jobs, allowlist
    if len(jobs) < max_states:
        raise ValueError(f"allowlist yielded {len(jobs)} states, requested {max_states}")
    return jobs, allowlist


def _save_array(directory: Path, name: str, value: np.ndarray) -> dict:
    path = directory / f"{name}.npy"
    np.save(path, np.ascontiguousarray(value), allow_pickle=False)
    return {
        "path": path.name,
        "dtype": np.dtype(value.dtype).str,
        "shape": list(value.shape),
        "sha256": _sha256(path),
    }


def build_shard(args) -> None:
    if args.output.exists() and any(args.output.iterdir()):
        raise FileExistsError(f"refusing non-empty output directory: {args.output}")
    args.output.mkdir(parents=True, exist_ok=True)
    if _sha256(args.binary) != args.binary_sha256:
        raise ValueError("teacher binary digest mismatch")
    jobs, allowlist = _source_jobs(args.allowlist, args.binary, args.max_states)
    os.environ.setdefault("OMP_NUM_THREADS", "1")
    started = time.perf_counter()
    states = []
    with ProcessPoolExecutor(max_workers=args.workers) as pool:
        futures = {pool.submit(_extract_state, job): job for job in jobs}
        for future in as_completed(futures):
            states.append(future.result())
    states.sort(key=lambda row: (row["seed"], row["opponent"], row["seat"]))
    extract_seconds = time.perf_counter() - started

    contract = states[0]["contract"]
    feature_names = states[0]["feature_names"]
    context_names = states[0]["context_names"]
    for state in states:
        if (state["contract"] != contract or state["feature_names"] != feature_names or
                state["context_names"] != context_names):
            raise RuntimeError("schema drift across extracted states")

    sys.path.insert(0, str(TOKENIZER_ROOT))
    from kaggrl.tokenizer import ObservationTokenizer
    from experiments.midgame_autofill_student import contains_private_identity

    tokenizer = ObservationTokenizer()
    encoded = []
    for state in states:
        if contains_private_identity(state["observation"]):
            raise ValueError("forbidden identity field in canonical observation")
        encoded.append(tokenizer.encode(state["observation"]))
    max_tokens = 320
    if max(row.num_tokens for row in encoded) > max_tokens:
        raise ValueError("token count exceeds fixed 320-token contract")
    state_count = len(states)
    context_width = len(context_names)
    feature_width = len(feature_names)
    packed_width = max(len(state["packed_observation"]) for state in states)
    candidate_count = sum(len(state["candidates"]) for state in states)

    arrays = {
        "causal_context": np.asarray([state["context"] for state in states], dtype="<f4"),
        "packed_observation": np.zeros((state_count, packed_width), dtype="<f8"),
        "observation_length": np.asarray(
            [len(state["packed_observation"]) for state in states], dtype="<u2"),
        "token_continuous": np.zeros((state_count, max_tokens, 24), dtype="<f4"),
        "token_type": np.zeros((state_count, max_tokens), dtype="u1"),
        "token_category_a": np.zeros((state_count, max_tokens), dtype="u1"),
        "token_category_b": np.zeros((state_count, max_tokens), dtype="u1"),
        "token_category_c": np.zeros((state_count, max_tokens), dtype="u1"),
        "token_x": np.zeros((state_count, max_tokens), dtype="u1"),
        "token_y": np.zeros((state_count, max_tokens), dtype="u1"),
        "token_owner": np.zeros((state_count, max_tokens), dtype="u1"),
        "token_count": np.asarray([row.num_tokens for row in encoded], dtype="<u2"),
        "state_candidate_offsets": np.zeros(state_count + 1, dtype="<u4"),
        "candidate_features": np.empty((candidate_count, feature_width), dtype="<f4"),
        "candidate_target": np.empty((candidate_count, 100), dtype="i1"),
        "candidate_prepared_index": np.empty(candidate_count, dtype="<u2"),
        "candidate_id": np.empty(candidate_count, dtype="<i2"),
        "candidate_key_hash128": np.empty((candidate_count, 16), dtype="u1"),
        "candidate_legal": np.ones(candidate_count, dtype="u1"),
        "short_score": np.empty(candidate_count, dtype="<f8"),
        "state_label_local": np.empty(state_count, dtype="u1"),
        "state_label_global": np.empty(state_count, dtype="<u4"),
        "split": np.empty(state_count, dtype="u1"),
        "group_hash128": np.empty((state_count, 16), dtype="u1"),
    }
    cursor = 0
    audit_groups = []
    categorical = ("token_type", "token_category_a", "token_category_b",
                   "token_category_c", "token_x", "token_y", "token_owner")
    encoded_fields = ("token_type", "category_a", "category_b", "category_c",
                      "x", "y", "owner")
    for index, (state, tokenized) in enumerate(zip(states, encoded)):
        exact = state["packed_observation"]
        arrays["packed_observation"][index, :len(exact)] = exact
        count = tokenized.num_tokens
        arrays["token_continuous"][index, :count] = tokenized.continuous.numpy()
        for target_name, source_name in zip(categorical, encoded_fields):
            arrays[target_name][index, :count] = getattr(tokenized, source_name).numpy()
        arrays["state_candidate_offsets"][index] = cursor
        for candidate in state["candidates"]:
            arrays["candidate_features"][cursor] = candidate["features"]
            arrays["candidate_target"][cursor] = candidate["target"]
            arrays["candidate_prepared_index"][cursor] = candidate["prepared_index"]
            arrays["candidate_id"][cursor] = candidate["candidate_id"]
            arrays["candidate_key_hash128"][cursor] = np.frombuffer(
                bytes.fromhex(candidate["key_hash128"]), dtype=np.uint8)
            arrays["short_score"][cursor] = candidate["short_score"]
            cursor += 1
        label_global = int(arrays["state_candidate_offsets"][index]) + state["winner_local"]
        arrays["state_label_local"][index] = state["winner_local"]
        arrays["state_label_global"][index] = label_global
        group = f'{state["seed"]}:{state["opponent"]}'
        group_digest = hashlib.sha256(group.encode()).digest()[:16]
        arrays["group_hash128"][index] = np.frombuffer(group_digest, dtype=np.uint8)
        arrays["split"][index] = int(group_digest[0] < 51)  # deterministic ~20% heldout
        audit_groups.append({
            "group_hash128": group_digest.hex(), "seed": state["seed"],
            "opponent_family": state["opponent"], "seat": state["seat"],
            "trajectory": state["trajectory"],
        })
    arrays["state_candidate_offsets"][-1] = cursor
    if cursor != candidate_count or not np.any(arrays["split"] == 0) or not np.any(arrays["split"] == 1):
        raise RuntimeError("invalid candidate offsets or empty train/heldout split")
    if np.any(arrays["candidate_legal"][arrays["state_label_global"]] != 1):
        raise RuntimeError("teacher selected an illegal candidate")

    array_manifest = {name: _save_array(args.output, name, value)
                      for name, value in arrays.items()}
    schema = {
        "schema_name": "candidate-selection-student-v1",
        "container": "numpy .npy mmap",
        "model_input_arrays": sorted(MODEL_INPUTS),
        "target_only_arrays": ["short_score", "state_label_local", "state_label_global"],
        "audit_only_arrays": ["candidate_prepared_index", "candidate_id",
                              "candidate_key_hash128", "group_hash128", "split"],
        "candidate_scope": "all normal R1 portfolios at first handoff step288",
        "label": "argmax short_score among normal candidates",
        "joint_bundle_coverage": "not covered",
        "identity_policy": "seed/opponent/seat are audit-only and absent from model inputs",
        "canonical_observation": "acting farm first, player fixed to zero",
    }
    manifest = {
        "format": "kaggriculture-midgame-mmap",
        "container_version": 1,
        "validation_status": "accepted",
        "schema": schema,
        "schema_sha256": _json_hash(schema),
        "byte_order": "little",
        "constants": {"step": 288, "terminal_action_exclusive": 719,
                      "turns_per_day": 24, "max_tokens": max_tokens},
        "counts": {"states": state_count, "candidates": candidate_count,
                   "train_states": int(np.sum(arrays["split"] == 0)),
                   "heldout_states": int(np.sum(arrays["split"] == 1))},
        "dimensions": {"causal_context": context_width,
                       "packed_observation": packed_width,
                       "candidate_features": feature_width},
        "arrays": array_manifest,
        "native_contract": contract,
        "candidate_feature_names": feature_names,
        "causal_context_names": context_names,
        "teacher_binary": str(args.binary.resolve()),
        "teacher_binary_sha256": args.binary_sha256,
        "tokenizer": str((TOKENIZER_ROOT / "kaggrl/tokenizer.py").resolve()),
        "tokenizer_sha256": _sha256(TOKENIZER_ROOT / "kaggrl/tokenizer.py"),
        "source_allowlist": str(args.allowlist.resolve()),
        "source_allowlist_sha256": _sha256(args.allowlist),
        "source_allowlist_payload_sha256": _json_hash(allowlist),
        "split_method": "sha256(seed:opponent_family)[0] < 51; whole group",
        "audit_groups": audit_groups,
        "validation": {
            "trajectory_steps_0_718": "PASS", "one_terminal": "PASS",
            "policy_digest": "PASS", "schema_hashes": "PASS",
            "candidate_key_stability": "PASS", "label_legal_fraction": 1.0,
            "no_identity_in_model_inputs": "PASS",
        },
        "timing": {"extract_seconds": extract_seconds,
                   "mean_short_score_seconds": float(np.mean(
                       [state["short_score_seconds"] for state in states]))},
    }
    temporary = args.output / "manifest.json.tmp"
    temporary.write_text(json.dumps(manifest, indent=2) + "\n")
    os.replace(temporary, args.output / "manifest.json")
    print(json.dumps({"status": "PASS", "output": str(args.output),
                      **manifest["counts"], **manifest["timing"]}))


def _load_shard(directory: Path):
    manifest_path = directory / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    if manifest.get("validation_status") != "accepted":
        raise ValueError("only accepted shards may be trained")
    arrays = {}
    for name, spec in manifest["arrays"].items():
        path = directory / spec["path"]
        if _sha256(path) != spec["sha256"]:
            raise ValueError(f"{name}: array digest mismatch")
        value = np.load(path, mmap_mode="r", allow_pickle=False)
        if list(value.shape) != spec["shape"] or value.dtype.str != spec["dtype"]:
            raise ValueError(f"{name}: dtype/shape mismatch")
        arrays[name] = value
    if set(manifest["schema"]["model_input_arrays"]) != MODEL_INPUTS:
        raise ValueError("model-input allowlist mismatch")
    offsets = arrays["state_candidate_offsets"]
    if offsets[0] != 0 or offsets[-1] != len(arrays["candidate_features"]) or np.any(offsets[1:] < offsets[:-1]):
        raise ValueError("invalid ragged candidate offsets")
    return manifest, arrays


def build_model(context_width: int, observation_width: int, candidate_width: int):
    import torch

    class CandidateStudent(torch.nn.Module):
        def __init__(self):
            super().__init__()
            self.context = torch.nn.Linear(context_width, 16)
            self.observation = torch.nn.Linear(observation_width, 16)
            vocabularies = (7, 32, 32, 32, 64, 64, 4)
            self.token_embeddings = torch.nn.ModuleList(
                torch.nn.Embedding(size, 4) for size in vocabularies)
            self.token = torch.nn.Linear(24 + 7 * 4, 16)
            self.candidate = torch.nn.Linear(candidate_width, 32)
            self.target_embedding = torch.nn.Embedding(14, 4, padding_idx=0)
            self.target = torch.nn.Linear(4, 8)
            self.head = torch.nn.Sequential(
                torch.nn.Linear(88, 48), torch.nn.ReLU(), torch.nn.Linear(48, 1))

        def encode_states(self, context, observation, token_continuous,
                          token_categories, token_count):
            positions = torch.arange(token_continuous.shape[1], device=context.device)[None]
            mask = positions < token_count[:, None]
            denominator = token_count.clamp_min(1).float()[:, None]
            continuous = (token_continuous * mask[:, :, None]).sum(1) / denominator
            embedded = []
            for table, values in zip(self.token_embeddings, token_categories):
                embedded.append((table(values) * mask[:, :, None]).sum(1) / denominator)
            tokens = torch.cat((continuous, *embedded), dim=1)
            return torch.cat((
                torch.relu(self.context(context)),
                torch.relu(self.observation(observation)),
                torch.relu(self.token(tokens)),
            ), dim=1)

        def forward(self, state_embedding, candidate_features, candidate_target):
            target = self.target_embedding((candidate_target.long() + 2).clamp(0, 13)).mean(1)
            values = torch.cat((state_embedding, torch.relu(self.candidate(candidate_features)),
                                torch.relu(self.target(target))), dim=1)
            return self.head(values).squeeze(1)

    return CandidateStudent()


def train(args) -> None:
    import torch
    import torch.nn.functional as functional

    manifest, arrays = _load_shard(args.shard)
    torch.manual_seed(args.seed)
    torch.set_num_threads(args.threads)
    split = np.asarray(arrays["split"])
    train_states = np.flatnonzero(split == 0)
    heldout_states = np.flatnonzero(split == 1)
    offsets_np = np.asarray(arrays["state_candidate_offsets"], dtype=np.int64)
    candidate_state_np = np.repeat(np.arange(len(split)), np.diff(offsets_np))
    train_candidates = np.isin(candidate_state_np, train_states)

    def standardize(value, rows):
        sample = np.asarray(value[rows], dtype=np.float32)
        mean = sample.mean(0, dtype=np.float64).astype(np.float32)
        std = sample.std(0, dtype=np.float64).astype(np.float32)
        std[std < 1e-5] = 1.0
        return mean, std

    context_mean, context_std = standardize(arrays["causal_context"], train_states)
    observation_mean, observation_std = standardize(arrays["packed_observation"], train_states)
    candidate_mean, candidate_std = standardize(arrays["candidate_features"], train_candidates)

    tensor = lambda value, dtype=None: torch.as_tensor(np.asarray(value).copy(), dtype=dtype)
    inputs = {
        "context": (tensor(arrays["causal_context"], torch.float32) - tensor(context_mean)) / tensor(context_std),
        "observation": (tensor(arrays["packed_observation"], torch.float32) - tensor(observation_mean)) / tensor(observation_std),
        "token_continuous": tensor(arrays["token_continuous"], torch.float32),
        "token_categories": [tensor(arrays[name], torch.long) for name in
                             ("token_type", "token_category_a", "token_category_b",
                              "token_category_c", "token_x", "token_y", "token_owner")],
        "token_count": tensor(arrays["token_count"], torch.long),
        "candidate_features": (tensor(arrays["candidate_features"], torch.float32) - tensor(candidate_mean)) / tensor(candidate_std),
        "candidate_target": tensor(arrays["candidate_target"], torch.long),
    }
    if set(inputs) != {"context", "observation", "token_continuous", "token_categories",
                       "token_count", "candidate_features", "candidate_target"}:
        raise RuntimeError("unexpected forward tensor")
    offsets = tensor(offsets_np, torch.long)
    candidate_state = tensor(candidate_state_np, torch.long)
    labels = tensor(arrays["state_label_local"], torch.long)

    def scores(model):
        state = model.encode_states(inputs["context"], inputs["observation"],
                                    inputs["token_continuous"], inputs["token_categories"],
                                    inputs["token_count"])
        return model(state[candidate_state], inputs["candidate_features"],
                     inputs["candidate_target"])

    def loss_and_top1(model, state_indices):
        logits = scores(model)
        losses = []
        correct = 0
        for state in state_indices:
            lo, hi = int(offsets[state]), int(offsets[state + 1])
            group = logits[lo:hi].unsqueeze(0)
            label = labels[state].reshape(1)
            losses.append(functional.cross_entropy(group, label))
            correct += int(group.argmax(1).item() == label.item())
        return torch.stack(losses).mean(), correct / len(state_indices)

    dimensions = manifest["dimensions"]
    make_model = lambda: build_model(dimensions["causal_context"],
                                     dimensions["packed_observation"],
                                     dimensions["candidate_features"])
    probe = make_model()
    parameters = sum(value.numel() for value in probe.parameters())
    if not 80_000 <= parameters <= 180_000:
        raise RuntimeError(f"model size {parameters} outside first-version budget")

    # One real batch only: this catches label/index/mask/model wiring errors.
    overfit_states = train_states[:min(8, len(train_states))]
    overfit = make_model()
    optimizer = torch.optim.Adam(overfit.parameters(), lr=0.02)
    first_overfit = None
    for _ in range(args.overfit_steps):
        optimizer.zero_grad(set_to_none=True)
        value, _ = loss_and_top1(overfit, overfit_states)
        if first_overfit is None:
            first_overfit = float(value.detach())
        value.backward()
        optimizer.step()
    overfit_loss, overfit_top1 = loss_and_top1(overfit, overfit_states)
    if not float(overfit_loss) < first_overfit or overfit_top1 < 0.999:
        raise RuntimeError("real one-batch overfit check failed")

    torch.manual_seed(args.seed)
    model = make_model()
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.learning_rate,
                                  weight_decay=1e-4)
    initial_train_loss, initial_train_top1 = loss_and_top1(model, train_states)
    initial_val_loss, initial_val_top1 = loss_and_top1(model, heldout_states)
    started = time.perf_counter()
    for _ in range(args.epochs):
        optimizer.zero_grad(set_to_none=True)
        value, _ = loss_and_top1(model, train_states)
        value.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0)
        optimizer.step()
    elapsed = time.perf_counter() - started
    train_loss, train_top1 = loss_and_top1(model, train_states)
    val_loss, val_top1 = loss_and_top1(model, heldout_states)
    if not float(train_loss) < float(initial_train_loss):
        raise RuntimeError("training loss did not decrease")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    checkpoint = {
        "model": model.state_dict(),
        "model_dimensions": dimensions,
        "normalization": {
            "context_mean": context_mean, "context_std": context_std,
            "observation_mean": observation_mean, "observation_std": observation_std,
            "candidate_mean": candidate_mean, "candidate_std": candidate_std,
        },
        "shard_manifest_sha256": _sha256(args.shard / "manifest.json"),
        "model_inputs": sorted(MODEL_INPUTS),
        "label_scope": "normal-candidate short-score selection only; no joint bundle",
    }
    torch.save(checkpoint, args.output)
    metrics = {
        "status": "PASS", "device": "cpu", "states": len(split),
        "candidates": len(candidate_state_np), "train_states": len(train_states),
        "heldout_states": len(heldout_states), "parameters": parameters,
        "label_legal_fraction": float(np.mean(arrays["candidate_legal"][arrays["state_label_global"]])),
        "one_batch_overfit": {"states": len(overfit_states), "initial_loss": first_overfit,
                              "final_loss": float(overfit_loss), "top1": overfit_top1},
        "train": {"initial_loss": float(initial_train_loss),
                  "initial_top1": initial_train_top1,
                  "final_loss": float(train_loss), "final_top1": train_top1},
        "heldout": {"initial_loss": float(initial_val_loss),
                    "initial_top1": initial_val_top1,
                    "final_loss": float(val_loss), "final_top1": val_top1},
        "timing": {"epochs": args.epochs, "seconds": elapsed,
                   "state_epochs_per_second": args.epochs * len(train_states) / elapsed},
        "checkpoint": str(args.output),
        "limitations": [
            "temporary target is R1 short-score selection, not terminal outcome",
            "normal complete portfolios only; joint-bundle/per-cell masks are not covered",
            "small smoke split measures pipeline correctness, not deployment quality",
        ],
    }
    metrics_path = args.output.with_suffix(".metrics.json")
    metrics_path.write_text(json.dumps(metrics, indent=2) + "\n")
    print(json.dumps(metrics))


def check_shard(args) -> None:
    manifest, arrays = _load_shard(args.shard)
    labels = arrays["state_label_global"]
    if not np.all(arrays["candidate_legal"][labels] == 1):
        raise RuntimeError("illegal label")
    print(json.dumps({"status": "PASS", **manifest["counts"],
                      "schema_sha256": manifest["schema_sha256"]}))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    build = subparsers.add_parser("build")
    build.add_argument("--allowlist", type=Path, required=True)
    build.add_argument("--binary", type=Path, required=True)
    build.add_argument("--binary-sha256", required=True)
    build.add_argument("--output", type=Path, required=True)
    build.add_argument("--max-states", type=int, default=48)
    build.add_argument("--workers", type=int, default=24)
    build.set_defaults(function=build_shard)
    fit = subparsers.add_parser("train")
    fit.add_argument("--shard", type=Path, required=True)
    fit.add_argument("--output", type=Path, required=True)
    fit.add_argument("--epochs", type=int, default=120)
    fit.add_argument("--overfit-steps", type=int, default=250)
    fit.add_argument("--learning-rate", type=float, default=0.003)
    fit.add_argument("--threads", type=int, default=8)
    fit.add_argument("--seed", type=int, default=20260922)
    fit.set_defaults(function=train)
    check = subparsers.add_parser("check")
    check.add_argument("--shard", type=Path, required=True)
    check.set_defaults(function=check_shard)
    args = parser.parse_args()
    if args.command == "build" and (args.max_states < 2 or args.workers < 1):
        parser.error("positive workers and at least two states required")
    args.function(args)


if __name__ == "__main__":
    main()
