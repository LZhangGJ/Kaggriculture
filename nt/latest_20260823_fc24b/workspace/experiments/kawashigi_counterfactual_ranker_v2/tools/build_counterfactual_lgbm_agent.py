#!/usr/bin/env python3
"""Build a standalone stdlib KAWASHIGI counterfactual route-value Agent."""

from __future__ import annotations

import argparse
import base64
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import zlib


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--training-receipt", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--receipt", type=Path, required=True)
    parser.add_argument("--version", default="kawashigi-counterfactual-lgbm-v1")
    args = parser.parse_args()
    source = args.source.read_text(encoding="utf-8").rstrip()
    model = json.loads(args.model.read_text(encoding="utf-8"))
    training = json.loads(args.training_receipt.read_text(encoding="utf-8"))
    if training.get("status") != "OOF_PASS_READY_FOR_FRESH_OFFICIAL":
        raise ValueError("training receipt did not pass OOF gate")
    selected = training["selected"]
    routes = tuple(model["routes"])
    if routes != ("10C-4S-75L", "8C-6S-75L", "6C-12S-100L", "6C-8S-75L"):
        raise ValueError(routes)
    if len(model["feature_names"]) != 66:
        raise ValueError(len(model["feature_names"]))
    packed = base64.b85encode(zlib.compress(json.dumps(model["models"], separators=(",", ":")).encode("utf-8"), level=9)).decode("ascii")
    suffix = f'''

# KAWASHIGI counterfactual route-value selector generated by
# build_counterfactual_lgbm_agent.py. Execution remains the frozen rule stream.
_KCR_ROUTES = {routes!r}
_KCR_THRESHOLD = {float(selected["threshold"])!r}
_KCR_DECISION_STEP = 145
_KCR_ANCHOR_STEPS = (73, 121)
_KCR_TREND_INDICES = (8, 11, 12, 14, 15, 23, 24, 27, 28)
_KCR_MODELS = json.loads(zlib.decompress(base64.b85decode({packed!r})).decode("utf-8"))
_KCR_HISTORY = {{0: {{}}, 1: {{}}}}
_KCR_BASE_CHOOSE_ROUTE = _cgr_choose_route
_KCR_BASE_AGENT = agent
__version__ = {args.version!r}


def _kcr_step(obs):
    value = _get(obs, "step", None)
    if value is not None:
        return min(max(0, int(value or 0)), 718)
    return min(max(0, int(_get(obs, "day", 0) or 0) * 24 + int(_get(obs, "hour", 0) or 0)), 718)


def _kcr_with_step(obs, step):
    if _get(obs, "step", None) is not None:
        return obs
    try:
        copied = dict(obs)
        copied["step"] = int(step)
        return copied
    except Exception:
        return obs


def _kcr_capture(obs, step):
    seat = _seat(obs)
    if step == 0:
        _KCR_HISTORY[seat] = {{}}
    if step in _KCR_ANCHOR_STEPS:
        _KCR_HISTORY[seat][step] = list(_cgr_features(obs))


def _kcr_extended_features(obs):
    seat = _seat(obs)
    current = list(_cgr_features(obs))
    values = list(current)
    history = _KCR_HISTORY.get(seat, {{}})
    for anchor_step in _KCR_ANCHOR_STEPS:
        anchor = history.get(anchor_step, current)
        values.extend(float(current[index] - anchor[index]) for index in _KCR_TREND_INDICES)
    return values


def _kcr_tree_value(node, values):
    while "leaf_value" not in node:
        feature = int(node["split_feature"])
        node = node["left_child"] if values[feature] <= float(node["threshold"]) else node["right_child"]
    return float(node["leaf_value"])


def _kcr_predict(route, values):
    return sum(_kcr_tree_value(tree["tree_structure"], values) for tree in _KCR_MODELS[route]["tree_info"])


def _kcr_scores(values):
    return [_kcr_predict(route, values) for route in _KCR_ROUTES]


def _kcr_choose_from_features(values, fallback):
    scores = _kcr_scores(values)
    best_index = max(range(len(scores)), key=lambda index: scores[index])
    fallback_index = _KCR_ROUTES.index(fallback)
    if scores[best_index] - scores[fallback_index] >= _KCR_THRESHOLD:
        return _KCR_ROUTES[best_index]
    return fallback


def _cgr_choose_route(obs):
    fallback = str(_KCR_BASE_CHOOSE_ROUTE(obs))
    return _kcr_choose_from_features(_kcr_extended_features(obs), fallback)


def agent(obs, configuration=None):
    step = _kcr_step(obs)
    obs = _kcr_with_step(obs, step)
    _kcr_capture(obs, step)
    return _KCR_BASE_AGENT(obs, configuration)


def kaggriculture_kawashigi_counterfactual_lgbm(obs, configuration=None):
    # Unique last-defined callable required by the filesystem Agent loader.
    return agent(obs, configuration)
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(source + suffix, encoding="utf-8", newline="\n")
    receipt = {
        "schema": "kawashigi-counterfactual-lgbm-agent-build-v1",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": "PASS",
        "source": str(args.source.resolve()),
        "source_sha256": sha256(args.source),
        "model": str(args.model.resolve()),
        "model_sha256": sha256(args.model),
        "training_receipt": str(args.training_receipt.resolve()),
        "training_receipt_sha256": sha256(args.training_receipt),
        "routes": list(routes),
        "decision_step": 145,
        "anchor_steps": [73, 121],
        "feature_count": 66,
        "threshold": float(selected["threshold"]),
        "training_source": str(selected["source"]),
        "runtime_dependencies": ["Python standard library only"],
        "output": str(args.output.resolve()),
        "output_sha256": sha256(args.output),
        "output_bytes": args.output.stat().st_size,
    }
    args.receipt.parent.mkdir(parents=True, exist_ok=True)
    args.receipt.write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(receipt, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
