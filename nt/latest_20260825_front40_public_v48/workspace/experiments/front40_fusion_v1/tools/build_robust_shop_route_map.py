"""Select first-shop routes that are robust across independent dev screens.

The ordinary selector maximizes pooled win rate.  With only a few events for a
shop, that can pick a route which is excellent on one random panel and poor on
another.  This tool keeps the same-source-first-shop safety constraint but
scores every eligible route on each screen separately.
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np


SHOP_NAMES = (
    "BAKERY",
    "BRUNCH_SPOT",
    "FARMERS_MARKET",
    "ICE_CREAM_SHOP",
    "PET_CAFE",
    "PIZZA_SHOP",
    "SMOOTHIE_SHOP",
    "YARN_STORE",
)


def wilson_lower_bound(wins: np.ndarray, games: np.ndarray) -> np.ndarray:
    z = 1.96
    p = wins / np.maximum(games, 1)
    denominator = 1.0 + z * z / np.maximum(games, 1)
    centre = p + z * z / (2.0 * np.maximum(games, 1))
    spread = z * np.sqrt(
        (p * (1.0 - p) + z * z / (4.0 * np.maximum(games, 1)))
        / np.maximum(games, 1)
    )
    return (centre - spread) / denominator


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--screens", type=Path, nargs="+", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--mode",
        choices=("minimax_win", "stable_win", "wilson"),
        required=True,
    )
    parser.add_argument(
        "--unrestricted",
        action="store_true",
        help="Allow every screened route to compete for every observed first shop.",
    )
    args = parser.parse_args()

    matrices = [np.load(path.with_suffix(".npz"), allow_pickle=False) for path in args.screens]
    reference = matrices[0]
    for matrix in matrices[1:]:
        for field in ("source_episode_id", "source_reward", "source_first_shop"):
            if not np.array_equal(reference[field], matrix[field]):
                raise RuntimeError(f"source field differs across screens: {field}")

    source_episode_id = np.asarray(reference["source_episode_id"])
    source_reward = np.asarray(reference["source_reward"])
    source_first_shop = np.asarray(reference["source_first_shop"])
    global_route_ids = np.asarray(
        reference["route_ids"] if "route_ids" in reference else np.arange(source_reward.size),
        dtype=np.int32,
    )
    if global_route_ids.shape != source_reward.shape:
        raise RuntimeError("route ID shape differs from source fields")
    for matrix in matrices[1:]:
        matrix_route_ids = np.asarray(
            matrix["route_ids"] if "route_ids" in matrix else np.arange(source_reward.size),
            dtype=np.int32,
        )
        if not np.array_equal(global_route_ids, matrix_route_ids):
            raise RuntimeError("route IDs differ across screens")
    route_ids: list[int] = []
    rows: list[dict[str, object]] = []

    for shop_id, shop_name in enumerate(SHOP_NAMES):
        eligible = (
            np.arange(source_first_shop.size)
            if args.unrestricted
            else np.flatnonzero(source_first_shop == shop_id)
        )
        if eligible.size == 0:
            raise RuntimeError(f"no source routes for {shop_name}")

        panel_wins: list[np.ndarray] = []
        panel_games: list[int] = []
        panel_win_rates: list[np.ndarray] = []
        panel_margins: list[np.ndarray] = []
        panel_invalid: list[np.ndarray] = []
        for matrix in matrices:
            first_shop = np.asarray(matrix["first_shop"])
            margin = np.asarray(matrix["margin"])
            invalid = np.asarray(matrix["invalid"])
            # The first visible shop is generated by the shared event bank and
            # is identical for both seats.  Keep both seat outcomes as games.
            event_mask = first_shop[0] == shop_id
            if not np.any(event_mask):
                continue
            group_margin = margin[:, event_mask, :][:, :, eligible].reshape(-1, eligible.size)
            group_invalid = invalid[:, event_mask, :][:, :, eligible].reshape(-1, eligible.size)
            wins = np.sum(group_margin > 0, axis=0)
            games = int(group_margin.shape[0])
            panel_wins.append(wins)
            panel_games.append(games)
            panel_win_rates.append(wins / games)
            panel_margins.append(np.mean(group_margin, axis=0))
            panel_invalid.append(np.mean(group_invalid, axis=0))
        if not panel_games:
            raise RuntimeError(f"no dev events for {shop_name}")

        win_matrix = np.stack(panel_win_rates, axis=0)
        margin_matrix = np.stack(panel_margins, axis=0)
        invalid_matrix = np.stack(panel_invalid, axis=0)
        wins_total = np.sum(np.stack(panel_wins, axis=0), axis=0)
        games_total = np.full(eligible.size, sum(panel_games), dtype=np.float64)
        pooled_win = wins_total / games_total
        pooled_margin = np.average(
            margin_matrix, axis=0, weights=np.asarray(panel_games, dtype=np.float64)
        )
        pooled_invalid = np.average(
            invalid_matrix, axis=0, weights=np.asarray(panel_games, dtype=np.float64)
        )
        worst_win = np.min(win_matrix, axis=0)
        worst_margin = np.min(margin_matrix, axis=0)
        win_std = np.std(win_matrix, axis=0)
        wilson = wilson_lower_bound(wins_total, games_total)

        if args.mode == "minimax_win":
            # Primary objective: do not collapse on any independent panel.
            keys = (
                source_reward[eligible],
                -pooled_invalid,
                pooled_margin,
                worst_margin,
                pooled_win,
                worst_win,
            )
        elif args.mode == "stable_win":
            stability_score = pooled_win - 0.5 * win_std
            keys = (
                source_reward[eligible],
                -pooled_invalid,
                pooled_margin,
                worst_win,
                stability_score,
            )
        else:
            keys = (
                source_reward[eligible],
                -pooled_invalid,
                pooled_margin,
                worst_win,
                wilson,
            )
        selected_local = int(np.lexsort(keys)[-1])
        selected_index = int(eligible[selected_local])
        selected = int(global_route_ids[selected_index])
        route_ids.append(selected)
        rows.append(
            {
                "shop_id": shop_id,
                "shop": shop_name,
                "route_id": selected,
                "source_episode_id": int(source_episode_id[selected_index]),
                "source_reward": int(source_reward[selected_index]),
                "training_games": int(games_total[selected_local]),
                "pooled_win_rate": float(pooled_win[selected_local]),
                "worst_panel_win_rate": float(worst_win[selected_local]),
                "panel_win_rates": [float(x) for x in win_matrix[:, selected_local]],
                "pooled_mean_margin": float(pooled_margin[selected_local]),
                "worst_panel_mean_margin": float(worst_margin[selected_local]),
                "pooled_invalid_mean": float(pooled_invalid[selected_local]),
                "wilson_lower_95": float(wilson[selected_local]),
            }
        )

    payload = {
        "schema": "kaggriculture.front40_fusion.robust-shop-route-map.v1",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "source_screens": [str(path) for path in args.screens],
        "shop_order": list(SHOP_NAMES),
        "route_ids": route_ids,
        "routes": rows,
        "selection_mode": args.mode,
        "unrestricted": args.unrestricted,
        "selection_rule": (
            "all screened routes eligible; panel-aware robust selection"
            if args.unrestricted
            else "same source first-shop required; panel-aware robust selection"
        ),
        "status": "TRAINING_ONLY",
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps({"status": "PASS", "mode": args.mode, "route_ids": route_ids}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
