def public_vector(observation):
    """Feature order is documented in provenance; no replay identity or seed."""
    market=observation['market']
    vector=[market['inventory'].get(item,10000)-10000 for item in PRODUCTS]
    vector.extend(market['prices'].get(item,0) for item in PRODUCTS)
    demand=[0]*9
    counts=[0]*8
    for shop in observation['town']['unlocked_shops']:
        if shop in SHOPS:
            j=SHOPS.index(shop);counts[j]+=1
            for item in SHOP_ITEMS[j]:demand[item]+=1
    vector.extend(demand);vector.extend(counts)
    seat=int(observation['player'])
    farm=observation['farms'][seat]
    rival=observation['farms'][1-seat]
    for side in (farm,rival):
        population=[0]*8
        for row in side['tiles']:
            for tile in row:
                if isinstance(tile,dict):
                    item=tile.get('crop') if tile.get('kind')=='PLANT' else tile.get('animal')
                    if item in POPULATION:population[POPULATION.index(item)]+=1
        vector.extend(population)
    vector.extend((farm['money'],rival['money'],farm['money']-rival['money']))
    vector.extend(observation['private']['shed'].get(item,0) for item in PRODUCTS)
    vector.append(len(farm['unlocked_quadrants']))
    return vector


def route_for(block,observation,previous):
    """Walk the block's tree: -2 tests the running schedule, -1 is a leaf."""
    tree=POLICY[block]
    node=0
    vector=None
    while True:
        feature,yes,no,route,cut=tree[node]
        if feature>=0:
            if vector is None:vector=public_vector(observation)
            node=yes if vector[feature]<=cut else no
        elif feature==-2:
            node=yes if previous==int(cut) else no
        else:
            return previous if route<0 else route


def market_order(order):
    """Emit an order slot in the form the engine itself can parse.

    Market orders race by slot index, so a slot the engine cannot parse is still
    a slot: it is skipped, not removed. Some donor schedules fill such a slot
    with ['PASS']. A zero-quantity sale is read as the same empty slot by the
    engine's own parser, and unlike ['PASS'] it survives tooling that discards
    unrecognised orders, so the slot cannot silently collapse.
    """
    if isinstance(order,list) and order:
        head=order[0]
        if head in ('HIRE','BUY_LAND'):return order[:]
        if head in ('BUY_SEED','BUY_PRODUCT','BUY_ANIMAL','SELL') and len(order)>2:
            try:
                if int(order[2])>0:return order[:]
            except (TypeError,ValueError):pass
    return ['SELL','WHEAT',0]


def agent(observation,configuration=None):
    """Return a fresh action object; route commitments persist within each block."""
    turn=int(observation['step']) if 'step' in observation else int(observation['day'])*24+int(observation['hour'])
    if turn<0 or turn>=719:return {'farmer':['PASS'],'hands':[],'market':[]}
    seat=int(observation['player'])
    block=turn//72
    state=sessions.get(seat)
    if state is None or turn<state['turn'] or turn==0:
        state={'turn':-1,'block':-1,'route':DEFAULT_ROUTE}
        sessions[seat]=state
    if state['block']!=block:
        state['route']=route_for(block,observation,state['route'])
        state['block']=block
    state['turn']=turn
    action=SCHEDULES[state['route']][turn]
    return {'farmer':action['farmer'][:] if isinstance(action['farmer'],list) and action['farmer'] else ['PASS'],
            'hands':[u[:] if isinstance(u,list) and u else ['PASS'] for u in action['hands']],
            'market':[market_order(order) for order in action['market'][:10]]}


